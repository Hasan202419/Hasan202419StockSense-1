    def start_perpetual_analysis(self, stock_universe: List[str]) -> None:
        """Start continuous market monitoring and analysis"""
        self.monitoring_active = True
        st.info("🤖 AI Trader: Starting perpetual market analysis...")
        
        # Create background thread for continuous monitoring
        def continuous_monitor():
            while self.monitoring_active:
                try:
                    self._perform_market_sweep(stock_universe)
                    time.sleep(300)  # Analyze every 5 minutes
                except Exception as e:
                    st.error(f"Monitoring error: {str(e)}")
                    time.sleep(60)
        
        # Start monitoring thread
        monitor_thread = threading.Thread(target=continuous_monitor, daemon=True)
        monitor_thread.start()
    
    def _perform_market_sweep(self, symbols: List[str]) -> None:
        """Perform comprehensive market analysis sweep"""
        current_time = datetime.now()
        
        for symbol in symbols:
            try:
                # Fetch real-time data
                ticker = yf.Ticker(symbol)
                info = ticker.info
                hist_data = ticker.history(period="3mo")
                
                if hist_data.empty or not info:
                    continue
                
                # Generate AI signal
                signal = self._generate_ai_signal(symbol, info, hist_data)
                
                if signal and signal.confidence > 0.75:  # High confidence signals only
                    self.market_signals.append(signal)
                    
                    # Execute trade if conditions are met
                    if signal.signal_type == "BUY" and self._should_execute_trade(signal):
                        self._execute_virtual_trade(signal)
                
            except Exception as e:
                continue
    
    def _generate_ai_signal(self, symbol: str, stock_info: Dict, hist_data: pd.DataFrame) -> Optional[MarketSignal]:
        """Generate sophisticated AI trading signal"""
        try:
            # Technical Analysis
            technical_score = self._analyze_technical_patterns(hist_data)
            
            # Fundamental Analysis
            fundamental_score = self._analyze_fundamentals(stock_info)
            
            # Momentum Analysis
            momentum_score = self._analyze_momentum(hist_data)
            
            # Market Psychology
            psychology_score = self._analyze_market_psychology(symbol, hist_data)
            
            # Combine scores with AI weighting
            combined_score = (
                technical_score * 0.35 +
                fundamental_score * 0.25 +
                momentum_score * 0.25 +
                psychology_score * 0.15
            )
            
            # Determine signal type
            if combined_score >= 75:
                signal_type = "BUY"
                confidence = min(combined_score / 100, 0.95)
            elif combined_score <= 30:
                signal_type = "SELL"
                confidence = min((100 - combined_score) / 100, 0.95)
            else:
                signal_type = "HOLD"
                confidence = 0.5
            
            # Calculate target price and stop loss
            current_price = stock_info.get('regularMarketPrice', 0)
            if current_price == 0:
                return None
            
            target_price, stop_loss = self._calculate_price_targets(
                current_price, signal_type, hist_data
            )
            
            # Generate reasoning
            reasoning = self._generate_signal_reasoning(
                technical_score, fundamental_score, momentum_score, psychology_score
            )
            
            # Risk assessment
            risk_level = self._assess_trade_risk(stock_info, hist_data)
            
            return MarketSignal(
                symbol=symbol,
                signal_type=signal_type,
                confidence=confidence,
                reasoning=reasoning,
                technical_score=technical_score,
                fundamental_score=fundamental_score,
                momentum_score=momentum_score,
                risk_level=risk_level,
                target_price=target_price,
                stop_loss=stop_loss,
                timestamp=datetime.now()
            )
            
        except Exception as e:
            return None
    
    def _analyze_technical_patterns(self, hist_data: pd.DataFrame) -> float:
        """Advanced technical pattern recognition"""
        if len(hist_data) < 50:
            return 50
        
        close_prices = hist_data['Close']
        volume = hist_data['Volume']
        
        score = 50  # Neutral start
        
        # Moving Average Analysis
        ma20 = close_prices.rolling(20).mean()
        ma50 = close_prices.rolling(50).mean()
        
        current_price = close_prices.iloc[-1]
        current_ma20 = ma20.iloc[-1]
        current_ma50 = ma50.iloc[-1]
        
        # Price above moving averages
        if current_price > current_ma20 > current_ma50:
            score += 15
        elif current_price > current_ma20:
            score += 8
        
        # Golden Cross pattern
        if (ma20.iloc[-1] > ma50.iloc[-1] and 
            ma20.iloc[-2] <= ma50.iloc[-2]):
            score += 20
        
        # Volume confirmation
        avg_volume = volume.rolling(20).mean().iloc[-1]
        current_volume = volume.iloc[-1]
        if current_volume > avg_volume * 1.5:
            score += 10
        
        # RSI analysis
        delta = close_prices.diff()
        gain = (delta.where(delta > 0, 0)).rolling(14).mean()
        loss = (-delta.where(delta < 0, 0)).rolling(14).mean()
        rs = gain / loss
        rsi = 100 - (100 / (1 + rs))
        current_rsi = rsi.iloc[-1]
        
        if 30 < current_rsi < 70:
            score += 8
        elif current_rsi < 30:
            score += 12  # Oversold opportunity
        
        # MACD analysis
        ema12 = close_prices.ewm(span=12).mean()
        ema26 = close_prices.ewm(span=26).mean()
        macd = ema12 - ema26
        signal_line = macd.ewm(span=9).mean()
        
        if macd.iloc[-1] > signal_line.iloc[-1] and macd.iloc[-2] <= signal_line.iloc[-2]:
            score += 15
        
        # Bollinger Bands squeeze detection
        bb_period = 20
        bb_std = 2
        bb_middle = close_prices.rolling(bb_period).mean()
        bb_std_dev = close_prices.rolling(bb_period).std()
        bb_upper = bb_middle + (bb_std_dev * bb_std)
        bb_lower = bb_middle - (bb_std_dev * bb_std)
        
        # Squeeze detection (low volatility before breakout)
        bb_width = (bb_upper - bb_lower) / bb_middle
        if bb_width.iloc[-1] < bb_width.rolling(20).mean().iloc[-1] * 0.8:
            score += 10  # Potential breakout setup
        
        return min(100, max(0, score))
    
