@dataclass
class TradePosition:
    """Represents a trading position"""
    symbol: str
    action: str  # BUY or SELL
    price: float
    quantity: int
    timestamp: datetime
    stop_loss: float
    target_price: float
    confidence: float
    reasoning: str

@dataclass
class MarketSignal:
    """Represents a market signal generated by AI"""
    symbol: str
    signal_type: str  # BUY, SELL, HOLD
    confidence: float
    reasoning: str
    technical_score: float
    fundamental_score: float
    momentum_score: float
    risk_level: str
    target_price: float
    stop_loss: float
    timestamp: datetime

class PerpetualAITrader:
    """Advanced AI Trading System with Continuous Market Analysis"""
    
